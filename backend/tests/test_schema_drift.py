"""Schema drift guard: model metadata must equal the migrated database.

INV-DB-3. ``alembic check`` diffs ``Base.metadata`` against a live database at
``head``; every reported difference is an operation that the next
``--autogenerate`` revision would apply.  Before T1.1 the diff contained
``remove_index`` for indexes that only exist in migrations, so autogenerate
silently produced DDL that dropped the title FTS/trigram indexes.

The database-backed check needs PostgreSQL that is already at ``head``; on
hosts without one the test skips and the container suite runs it (same pattern
as ``test_alembic_0039.py``).
"""

import asyncio
from pathlib import Path

import pytest
from alembic.config import Config
from sqlalchemy import bindparam, text
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import command
from galleryvault.config import get_settings
from galleryvault.db.models import Base

BACKEND_ROOT = Path(__file__).resolve().parent.parent

# Indexes created by hand-written migrations (0001 initial, 0015 trigram) that
# the ORM models must declare so autogenerate does not treat them as stale.
MIGRATION_ONLY_INDEXES = {
    ("galleries", "idx_galleries_title_fts"),
    ("galleries", "idx_galleries_title_trgm"),
    ("galleries", "idx_galleries_title_jpn_trgm"),
    ("download_tasks", "idx_download_tasks_gid"),
    ("download_tasks", "idx_download_tasks_status"),
}


def _alembic_config() -> Config:
    # Deliberately built without ``alembic.ini``: env.py calls
    # ``logging.config.fileConfig`` for it, and fileConfig disables existing
    # loggers by default, which would break ``caplog`` for every later test in
    # the same xdist worker.  script_location is all the check needs.
    config = Config()
    config.set_main_option("script_location", str(BACKEND_ROOT / "alembic"))
    return config


async def _index_names_in_database(url: str, names: list[str]) -> set[str]:
    engine = create_async_engine(url)
    try:
        async with engine.connect() as conn:
            rows = await conn.execute(
                text(
                    "SELECT indexname FROM pg_indexes WHERE indexname IN :names"
                ).bindparams(bindparam("names", expanding=True)),
                {"names": names},
            )
            return {row[0] for row in rows}
    finally:
        await engine.dispose()


def _run_async(coro):
    try:
        return asyncio.run(coro)
    except Exception as exc:  # noqa: BLE001 - no database on this host
        pytest.skip(f"Database connection unavailable: {exc}")


def test_models_declare_migration_only_indexes():
    """The five migration-created indexes must be present in metadata."""
    declared = {
        (table.name, index.name): index
        for table in Base.metadata.tables.values()
        for index in table.indexes
    }

    missing = sorted(key for key in MIGRATION_ONLY_INDEXES if key not in declared)
    assert missing == []

    fts = declared[("galleries", "idx_galleries_title_fts")]
    assert fts.dialect_options["postgresql"]["using"] == "gin"
    assert "to_tsvector" in str(fts.expressions[0])

    trigram = {
        "idx_galleries_title_trgm": "title",
        "idx_galleries_title_jpn_trgm": "title_jpn",
    }
    for name, column in trigram.items():
        index = declared[("galleries", name)]
        assert index.dialect_options["postgresql"]["using"] == "gin"
        assert index.dialect_options["postgresql"]["ops"] == {column: "gin_trgm_ops"}

    for name, column in (
        ("idx_download_tasks_gid", "gid"),
        ("idx_download_tasks_status", "status"),
    ):
        index = declared[("download_tasks", name)]
        assert index.unique is False
        assert index.columns.keys() == [column]


def test_alembic_check_reports_no_new_upgrade_operations():
    """``alembic check`` against the live database must find no drift."""
    url = get_settings().database_url

    async def _probe():
        engine = create_async_engine(url)
        try:
            async with engine.connect() as conn:
                await conn.execute(text("SELECT 1"))
        finally:
            await engine.dispose()

    _run_async(_probe())

    # Raises AutogenerateDiffsDetected when models and database disagree.
    command.check(_alembic_config())


def test_migration_indexes_still_exist_in_database():
    """Drift-free models must not have been reached by dropping the indexes."""
    url = get_settings().database_url
    names = sorted(name for _, name in MIGRATION_ONLY_INDEXES)

    found = _run_async(_index_names_in_database(url, names))

    assert found == set(names)
